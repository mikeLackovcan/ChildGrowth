const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const source = fs.readFileSync(require('node:path').join(__dirname,'../src/lib/brandMigration.ts'),'utf8');
const code = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const mod = {exports:{}};
new Function('exports','module',code)(mod.exports,mod);
const {normalizeBrandState,normalizeAvatarId} = mod.exports;
const old = {currentAvatar:'roblox_bacon_hair',unlockedAvatars:['default','roblox_noob','roblox_bacon_hair'],coins:1234,prizes:['Robux 💰','Custom reward'],wonPrizes:[{id:'1',prize:'Robux 💰',redeemed:true}],children:[{currentAvatar:'roblox_bloxy',unlockedAvatars:['roblox_bloxy']}]};
const result=normalizeBrandState(old);
assert.equal(result.currentAvatar,'quest_ember');
assert.deepEqual(result.unlockedAvatars,['default','quest_sprout','quest_ember']);
assert.equal(result.coins,1234);
assert.deepEqual(result.prizes,['Family surprise 🎁','Custom reward']);
assert.deepEqual(result.wonPrizes,[{id:'1',prize:'Family surprise 🎁',redeemed:true}]);
assert.equal(result.children[0].currentAvatar,'quest_sunrise');
assert.equal(old.currentAvatar,'roblox_bacon_hair');
assert.deepEqual(normalizeBrandState(result),result);
assert.equal(normalizeAvatarId('future_custom'),'future_custom');
assert.deepEqual(normalizeBrandState({current_avatar:'roblox_guest',unlocked_avatars:['roblox_guest']}),{current_avatar:'quest_drift',unlocked_avatars:['quest_drift']});
console.log('Brand migration: all assertions passed (unlocks, rewards, nested profiles, preservation, idempotence).');
