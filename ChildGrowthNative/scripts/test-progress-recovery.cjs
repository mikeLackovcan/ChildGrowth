const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), ts = require('typescript');
const memory = new Map(), auth = { currentUser: { uid: 'backup-child' } };
let failBackup = false;
const storage = { getItem: async key => memory.get(key) || null, removeItem: async key => memory.delete(key), setItem: async (key, value) => {
  if (failBackup && key.startsWith('questblox-legacy-progress-backup:')) throw Error('disk full'); memory.set(key, value);
} };
const moduleObject = { exports: {} };
const js = ts.transpileModule(fs.readFileSync(path.resolve(__dirname, '../src/lib/progressRecovery.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
vm.runInThisContext(`(function(require,module,exports){${js}\n})`)(name => {
  if (name.includes('async-storage')) return storage;
  if (name === './firebase') return { auth };
  throw Error(`Unexpected dependency ${name}`);
}, moduleObject, moduleObject.exports);
const { preserveLegacySave, preserveFamilyCache, readLegacyBackups } = moduleObject.exports;
(async () => {
  const marker = 'pending-cloud:user_data/backup-child';
  const raw = JSON.stringify({ fields: { coins: 123, tasks: [{ id: 'old', name: 'Read' }] } });
  memory.set(marker, raw); memory.set('pending-family:backup-child', '1');
  const local = { userId: 'backup-child', coins: 123, tasks: [{ id: 'old', name: 'Read' }], save() {} };
  failBackup = true;
  await assert.rejects(preserveLegacySave('backup-child', local), /disk full/);
  assert.equal(memory.get(marker), raw); assert.equal(memory.get('pending-family:backup-child'), '1');
  failBackup = false;
  await preserveLegacySave('backup-child', local);
  assert.equal(memory.has(marker), false); assert.equal(memory.has('pending-family:backup-child'), false);
  const backups = await readLegacyBackups('backup-child');
  assert.equal(backups.length, 1); assert.equal(backups[0].pending[marker], raw); assert.equal(backups[0].local.coins, 123);
  assert.equal(backups[0].local.tasks[0].name, 'Read'); assert.equal(backups[0].local.save, undefined);
  await preserveLegacySave('backup-child', local);
  assert.equal((await readLegacyBackups('backup-child')).length, 1);
  console.log('✓ Exact legacy data is backed up before markers are cleared; failed writes preserve the recovery block');
  memory.set(marker, raw);
  const family = { ...local, children: [{ id: 'old-child', coins: 777, tasks: [{ id: 'family-task' }] }] };
  failBackup = true;
  await assert.rejects(preserveFamilyCache('backup-child', family), /disk full/);
  assert.equal(memory.get(marker), raw);
  failBackup = false;
  await preserveFamilyCache('backup-child', family);
  await preserveFamilyCache('backup-child', family);
  const familyCopies = (await readLegacyBackups('backup-child')).filter(item => item.pending.familyVerification);
  assert.equal(familyCopies.length, 1); assert.equal(familyCopies[0].local.children[0].coins, 777);
  assert.equal(memory.get(marker), raw);
  console.log('✓ Family verification preserves one exact backup without releasing pending save markers');
  auth.currentUser = { uid: 'another-child' };
  await assert.rejects(readLegacyBackups('backup-child'), /ACCOUNT_CHANGED/);
  await assert.rejects(preserveFamilyCache('backup-child', family), /ACCOUNT_CHANGED/);
  await assert.rejects(preserveLegacySave('backup-child', local), /ACCOUNT_CHANGED/);
  await assert.rejects(preserveLegacySave('another-child', local), /ACCOUNT_CHANGED/);
  console.log('✓ Legacy backups cannot cross account boundaries or be attributed to a different account');
})().catch(error => { console.error(error); process.exitCode = 1; });
