import { onCall, HttpsError } from 'firebase-functions/v2/https';
import { authenticated, db, digest, linkId, text } from './core';

const friendlyWords = {
  first: ['astro', 'blaze', 'brave', 'cosmic', 'frost', 'hyper', 'lucky', 'mega', 'pixel', 'rapid', 'solar', 'turbo'],
  second: ['bear', 'fox', 'hero', 'koala', 'ninja', 'otter', 'panda', 'raven', 'tiger', 'wolf', 'wizard', 'yeti'],
};

function nicknameStem(fullName: unknown) {
  if (typeof fullName !== 'string') return '';
  return fullName.trim().split(/\s+/)[0].normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 10);
}

function friendlyNickname(uid: string, fullName?: unknown) {
  const hash = digest(uid);
  const fallback = friendlyWords.second[parseInt(hash.slice(0, 4), 16) % friendlyWords.second.length];
  const stem = nicknameStem(fullName) || fallback;
  const number = 1000 + (parseInt(hash.slice(8, 16), 16) % 9000);
  return `${stem}${number}`;
}

function isOldGeneratedNickname(nickname: unknown) {
  if (typeof nickname !== 'string') return false;
  if (/^hero_[a-f0-9]{16}$/.test(nickname)) return true;
  return friendlyWords.first.some(first => friendlyWords.second.some(second => nickname.match(new RegExp(`^${first}${second}\\d{4}$`))));
}

export const initializeAccount = onCall(async request => {
  const uid = authenticated(request);
  const email = typeof request.auth?.token.email === 'string' ? request.auth.token.email.toLowerCase() : '';
  if (!email || request.auth?.token.firebase?.sign_in_provider === 'anonymous') throw new HttpsError('permission-denied', 'ACCOUNT_SIGN_IN_REQUIRED');
  const role = request.data?.role;
  if (!['child', 'parent'].includes(role)) throw new HttpsError('invalid-argument', 'INVALID_ROLE');
  const suppliedFullName = typeof request.data?.fullName === 'string' ? request.data.fullName.trim().slice(0, 80) : '';
  const nickname = request.data?.nickname === undefined ? friendlyNickname(uid, suppliedFullName) : text(request.data.nickname, 24).toLowerCase().replace(/^@/, '');
  if (!/^[a-z0-9_-]{3,24}$/.test(nickname)) throw new HttpsError('invalid-argument', 'INVALID_NICKNAME');
  const fullName = suppliedFullName || nickname;
  await db.runTransaction(async transaction => {
    const profileRef = db.doc(`profiles/${uid}`), existing = await transaction.get(profileRef);
    // Sign-in is not an opportunity to replace identity, role or saved progress.
    if (existing.exists) return;
    const nameRef = db.doc(`nicknames/${nickname}`);
    const [reserved, legacyMatches, data] = await Promise.all([
      transaction.get(nameRef), transaction.get(db.collection('profiles').where('nickname', '==', nickname).limit(1)),
      transaction.get(db.doc(`user_data/${uid}`)),
    ]);
    if ((reserved.exists && reserved.data()?.uid !== uid) || !legacyMatches.empty) throw new HttpsError('already-exists', 'NICKNAME_TAKEN');
    if (data.exists) throw new HttpsError('failed-precondition', 'ACCOUNT_RECOVERY_REQUIRED');
    const updated_at = new Date().toISOString();
    transaction.create(profileRef, { email, full_name: fullName || nickname, nickname, nickname_generated: request.data?.nickname === undefined, role,
      coins: 0, xp: 0, level: 1, current_avatar: 'roblox_noob', updated_at });
    transaction.set(nameRef, { uid });
    transaction.create(db.doc(`user_data/${uid}`), { tasks: [], prizes: [], won_prizes: [], children: [],
      linked_parents: [], unlocked_avatars: ['roblox_noob'], updated_at });
  });
  return { ok: true };
});

export const updateNickname = onCall(async request => {
  const uid = authenticated(request);
  const requested = request.data?.nickname;
  return db.runTransaction(async transaction => {
    const profileRef = db.doc(`profiles/${uid}`);
    const profileSnap = await transaction.get(profileRef);
    if (!profileSnap.exists) throw new HttpsError('failed-precondition', 'ACCOUNT_SIGN_IN_REQUIRED');
    const profile = profileSnap.data() || {};
    const oldNickname = profile.nickname;
    const nextNickname = requested === undefined ? friendlyNickname(uid, profile.full_name) : text(requested, 24).toLowerCase().replace(/^@/, '');
    if (!/^[a-z0-9_-]{3,24}$/.test(nextNickname) || nextNickname.startsWith('hero_')) {
      throw new HttpsError('invalid-argument', 'INVALID_NICKNAME');
    }
    if (oldNickname === nextNickname) return { nickname: nextNickname };
    // An omitted nickname only refreshes names generated by Questblox.
    if (requested === undefined && !profile.nickname_generated && !isOldGeneratedNickname(oldNickname)) {
      return { nickname: oldNickname };
    }
    const nextRef = db.doc(`nicknames/${nextNickname}`);
    const oldRef = typeof oldNickname === 'string' ? db.doc(`nicknames/${oldNickname}`) : null;
    const [reserved, legacyMatches, oldReservation] = await Promise.all([
      transaction.get(nextRef),
      transaction.get(db.collection('profiles').where('nickname', '==', nextNickname).limit(1)),
      oldRef ? transaction.get(oldRef) : Promise.resolve(null),
    ]);
    if ((reserved.exists && reserved.data()?.uid !== uid) || (!legacyMatches.empty && legacyMatches.docs[0].id !== uid)) {
      throw new HttpsError('already-exists', 'NICKNAME_TAKEN');
    }
    transaction.set(nextRef, { uid });
    transaction.update(profileRef, { nickname: nextNickname, nickname_generated: requested === undefined,
      ...((profile.full_name === oldNickname || (typeof profile.full_name === 'string' && /^hero_/i.test(profile.full_name))) ? { full_name: nextNickname } : {}),
      updated_at: new Date().toISOString() });
    if (oldRef && oldNickname !== nextNickname) {
      if (oldReservation?.data()?.uid === uid) transaction.delete(oldRef);
    }
    return { nickname: nextNickname };
  });
});

// A nickname may be used to find an already accepted family account, but never
// to enumerate private profiles or read another family's email/progress.
export const resolveFamilyAccount = onCall(async request => {
  const uid = authenticated(request), tag = text(request.data?.tag, 254).toLowerCase().replace(/^@/, '');
  const matches = await db.collection('profiles').where(tag.includes('@') ? 'email' : 'nickname', '==', tag).limit(2).get();
  if (matches.size !== 1) throw new HttpsError('not-found', 'FAMILY_ACCOUNT_UNAVAILABLE');
  const otherId = matches.docs[0].id;
  if (otherId === uid) return { uid };
  const [parentLink, childLink] = await Promise.all([
    db.doc(`familyLinks/${linkId(uid, otherId)}`).get(), db.doc(`familyLinks/${linkId(otherId, uid)}`).get(),
  ]);
  if (parentLink.data()?.status !== 'accepted' && childLink.data()?.status !== 'accepted') throw new HttpsError('not-found', 'FAMILY_ACCOUNT_UNAVAILABLE');
  return { uid: otherId };
});

export const recoverLegacyProgress = onCall(async request => {
  const uid = authenticated(request);
  return db.runTransaction(async transaction => {
    const ref = db.doc(`user_data/${uid}`);
    const [profile, current] = await Promise.all([transaction.get(db.doc(`profiles/${uid}`)), transaction.get(ref)]);
    if (current.exists) return { migrated: false };
    const nickname = profile.data()?.nickname;
    if (typeof nickname !== 'string' || !/^[a-z0-9_-]{3,24}$/.test(nickname)) return { migrated: false };
    const [legacy, owners] = await Promise.all([
      transaction.get(db.doc(`user_data/usr_${nickname}`)),
      transaction.get(db.collection('profiles').where('nickname', '==', nickname).limit(2)),
    ]);
    if (!legacy.exists) return { migrated: false };
    const data = legacy.data()!;
    if (owners.size !== 1 || owners.docs[0].id !== uid || (data.userId && data.userId !== uid) || (data.ownerUid && data.ownerUid !== uid)) {
      throw new HttpsError('failed-precondition', 'ACCOUNT_RECOVERY_REQUIRED');
    }
    // Preserve historical progress, but never turn old client-written family
    // summaries into server access grants. The source remains intact as backup.
    const fields = ['tasks', 'prizes', 'won_prizes', 'unlocked_avatars', 'children', 'linked_parents', 'parent_email', 'approval_status',
      'lastActiveDate', 'lastSpinDate', 'epicClaimedDate', 'dailyChestClaimedDate', 'superchargedTaskId', 'dailyMood', 'isSick', 'streak',
      'activeTheme', 'unlockedThemes', 'epicBossTask', 'epicBossXP'];
    transaction.create(ref, { ...Object.fromEntries(fields.filter(key => data[key] !== undefined).map(key => [key, data[key]])), updated_at: new Date().toISOString() });
    return { migrated: true };
  });
});

// Read-only projection: historical client-written summaries remain available as
// recovery evidence, but cannot make an unverified family look connected.
export const getFamilyStatus = onCall(async request => {
  const uid = authenticated(request);
  const [profileSnap, dataSnap, asParent, asChild] = await Promise.all([
    db.doc(`profiles/${uid}`).get(), db.doc(`user_data/${uid}`).get(),
    db.collection('familyLinks').where('parentUid', '==', uid).get(),
    db.collection('familyLinks').where('childUid', '==', uid).get(),
  ]);
  const profile = profileSnap.data(), data = dataSnap.data() || {};
  if (!profile || !['parent', 'child'].includes(profile.role)) throw new HttpsError('failed-precondition', 'ACCOUNT_SIGN_IN_REQUIRED');
  const links = (profile.role === 'parent' ? asParent : asChild).docs.map(doc => doc.data());
  const children: any[] = [], parents: string[] = [], known = new Set<string>();
  let pendingParent: string | null = null;
  let pendingInvitation: { name: string; nickname: string; sentByMe: boolean } | null = null;
  for (const link of links) {
    const otherUid = profile.role === 'parent' ? link.childUid : link.parentUid;
    if (typeof otherUid !== 'string' || otherUid.includes('/')) continue;
    const other = (await db.doc(`profiles/${otherUid}`).get()).data();
    if (!other || other.role !== (profile.role === 'parent' ? 'child' : 'parent') || typeof other.nickname !== 'string') continue;
    known.add(other.nickname);
    if (!['pending', 'accepted'].includes(link.status)) continue;
    const accepted = link.status === 'accepted';
    if (profile.role === 'child' && accepted) parents.push(other.nickname);
    if (profile.role === 'child' && !accepted) {
      pendingParent ||= other.nickname;
      pendingInvitation ||= { name: other.full_name || other.nickname, nickname: other.nickname, sentByMe: link.invitedBy === uid };
    }
    // The child's invitation screen uses the same summary shape as the parent.
    const child = profile.role === 'parent' ? other : profile;
    children.push({ id: profile.role === 'parent' ? otherUid : uid,
      name: child.full_name || child.nickname, nickname: child.nickname,
      isApproved: accepted, initiatedBy: link.invitedBy === link.parentUid ? 'parent' : 'kid',
      linkedParents: [profile.role === 'parent' ? profile.nickname : other.nickname],
      level: accepted ? child.level || 1 : 1, xp: accepted ? child.xp || 0 : 0, coins: accepted ? child.coins || 0 : 0,
      tasks: [], prizes: [], wonPrizes: [], unlockedAvatars: ['roblox_noob'], currentAvatar: accepted ? child.current_avatar || 'roblox_noob' : 'roblox_noob' });
  }
  const oldTags = profile.role === 'parent' ? (Array.isArray(data.children) ? data.children : []).map((child: any) => child?.nickname) : [...(Array.isArray(data.linked_parents) ? data.linked_parents : []), data.parent_email];
  const familyReconnectTags = [...new Set<string>(oldTags.filter((tag: unknown): tag is string => typeof tag === 'string' && /^[a-z0-9_-]{3,24}$/.test(tag) && !known.has(tag)))];
  return { children, linked_parents: parents, parent_email: parents[0] || pendingParent,
    approval_status: parents.length ? 'approved' : pendingParent ? 'pending' : null,
    pending_invitation: pendingInvitation, familyReconnectTags };
});
